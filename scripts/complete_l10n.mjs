import fs from 'fs';
import path from 'path';

const l10nDir = path.join('lib', 'l10n');

function loadArb(file) {
  return JSON.parse(fs.readFileSync(path.join(l10nDir, file), 'utf8'));
}

function saveArb(file, data) {
  fs.writeFileSync(
    path.join(l10nDir, file),
    JSON.stringify(data, null, 2) + '\n',
    'utf8',
  );
}

function stringKeys(arb) {
  return Object.keys(arb).filter((k) => !k.startsWith('@') && typeof arb[k] === 'string');
}

